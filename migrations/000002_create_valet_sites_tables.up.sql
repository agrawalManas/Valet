CREATE TABLE IF NOT EXISTS sites(
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    is_booking_allowed BOOLEAN DEFAULT true,
    site_name VARCHAR(255) NOT NULL,
    pin_code NUMERIC NOT NULL,
    city VARCHAR(255) NOT NULL,
    state VARCHAR(255) NOT NULL,
    address_line_1 VARCHAR(255) NOT NULL,
    address_line_2 VARCHAR(255),
    site_coordinates NUMERIC(10, 10),
    supervisor_mobile_number VARCHAR(255) NOT NULL,
    supervisor_dob VARCHAR(255) NOT NULL,
    supervisor_gender VARCHAR(255) NOT NULL,
    supervisor_name VARCHAR (255) NOT NULL,
    site_images VARCHAR[],
    site_opening_time TIMESTAMPTZ NOT NULL,
    site_closing_time TIMESTAMPTZ NOT NULL,
    total_capacity NUMERIC NOT NULL,
    valet_fee NUMERIC NOT NULL,
    insurance_add_on_allowed BOOLEAN DEFAULT false,
    insurance_add_on_price NUMERIC,
    tipping_allowed BOOLEAN DEFAULT true,
    tipping_amount NUMERIC[],
    pick_tipping_allowed BOOLEAN DEFAULT true, 
    drop_tipping_allowed BOOLEAN DEFAULT true,
    parking_type VARCHAR(255) DEFAULT 'OTHER'
                 CHECK (parking_type IN ('BASEMENT', 'GROUND', 'OTHER')), 
    driver_count NUMERIC NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);